#!/usr/bin/env python3
"""Generate the Chick Run Chinese font subsets (LVGL format).

Why a script instead of committing the source font: Noto Sans SC is 8.3 MB and
only ~45 of its glyphs are used. The script fetches the pinned upstream file,
verifies its SHA-256, extracts the character inventory from the application's
single source of truth (main/chick_run_text.h) plus printable ASCII, and runs
the pinned lv_font_conv for every size the UI needs.

Run from the repository root:

    python3 tools/generate-chick-run-font.py

Outputs (tracked, compiled into the firmware):
    assets/fonts/chick_run_font_20.c
    assets/fonts/chick_run_font_28.c
    assets/fonts/chick_run_glyphs.txt     (the exact inventory, for review)
"""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEXT_HEADER = ROOT / "main" / "chick_run_text.h"
OUT_DIR = ROOT / "assets" / "fonts"

SOURCE_URL = (
    "https://raw.githubusercontent.com/notofonts/noto-cjk/main/"
    "Sans/SubsetOTF/SC/NotoSansSC-Regular.otf"
)
SOURCE_VERSION = "noto-cjk main / Sans/SubsetOTF/SC/NotoSansSC-Regular.otf"
SOURCE_SHA256 = "faa6c9df652116dde789d351359f3d7e5d2285a2b2a1f04a2d7244df706d5ea9"
SOURCE_LICENSE = "SIL Open Font License 1.1 (see notofonts/noto-cjk LICENSE)"
CONVERTER = "lv_font_conv@1.5.3"
# font sizes the UI uses: 20 px body/hints, 28 px title and HUD score
SIZES = (14, 20, 28)
ASCII_RANGE = "0x20-0x7E"


def inventory() -> list[str]:
    """Printable ASCII plus every non-ASCII character in the UI text header."""
    text = TEXT_HEADER.read_text(encoding="utf-8")
    # 文案登记在 main/chick_run_text.h:小鸡快跑(CHICK_)、方向快手(POCKET_)、
    # 番茄闹钟(POMODORO_)三个应用共用这一份"会显示什么字"的唯一来源。
    definitions = re.findall(
        r'#define\s+(?:CHICK|POCKET|POMODORO)_TEXT_\w+\s+"((?:[^"\\]|\\.)*)"', text
    )
    characters = {chr(code) for code in range(0x20, 0x7F)}
    for definition in definitions:
        characters.update(char for char in definition if ord(char) > 0x7F)
    return sorted(characters)


def ensure_source_font(cache: Path) -> Path:
    if cache.is_file():
        digest = hashlib.sha256(cache.read_bytes()).hexdigest()
        if digest == SOURCE_SHA256:
            return cache
        print(f"cached font hash mismatch, re-downloading: {cache}")
    cache.parent.mkdir(parents=True, exist_ok=True)
    print(f"downloading {SOURCE_URL}")
    with urllib.request.urlopen(SOURCE_URL, timeout=120) as response:
        payload = response.read()
    digest = hashlib.sha256(payload).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(
            f"downloaded font hash mismatch:\n  expected {SOURCE_SHA256}\n  actual   {digest}"
        )
    cache.write_bytes(payload)
    return cache


def generate(font_path: Path, size: int, symbols: str) -> Path:
    name = f"chick_run_font_{size}"
    output = OUT_DIR / f"{name}.c"
    command = [
        "npx", "--yes", CONVERTER,
        "--font", str(font_path),
        "--range", ASCII_RANGE,
        "--symbols", symbols,
        "--size", str(size),
        "--bpp", "4",
        "--format", "lvgl",
        "--no-compress",
        "--lv-font-name", name,
        "--lv-include", "lvgl.h",
        "--output", str(output),
    ]
    print(f"generating {output.name} ...")
    subprocess.run(command, check=True)
    return output


def main() -> int:
    if shutil.which("npx") is None:
        print("ERROR: npx is required to run lv_font_conv", file=sys.stderr)
        return 1

    characters = inventory()
    symbols = "".join(char for char in characters if ord(char) > 0x7F)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    cache = Path("/tmp/NotoSansSC-Regular.otf")
    font_path = ensure_source_font(cache)

    OUT_DIR.joinpath("chick_run_glyphs.txt").write_text(
        "# Chick Run font inventory (generated by tools/generate-chick-run-font.py)\n"
        f"# source: {SOURCE_VERSION}\n"
        f"# source sha256: {SOURCE_SHA256}\n"
        f"# license: {SOURCE_LICENSE}\n"
        f"# converter: {CONVERTER} --bpp 4 --no-compress --range {ASCII_RANGE}\n"
        f"# sizes: {' '.join(str(size) for size in SIZES)}\n"
        f"# ascii: 0x20-0x7E\n"
        f"# cjk ({len(symbols)}): {symbols}\n",
        encoding="utf-8",
    )

    for size in SIZES:
        output = generate(font_path, size, symbols)
        print(f"  {output.relative_to(ROOT)}: {output.stat().st_size} bytes")
    print(f"inventory: {len(symbols)} CJK characters + printable ASCII")
    print("now rebuild so main/CMakeLists.txt picks up the generated sources.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
